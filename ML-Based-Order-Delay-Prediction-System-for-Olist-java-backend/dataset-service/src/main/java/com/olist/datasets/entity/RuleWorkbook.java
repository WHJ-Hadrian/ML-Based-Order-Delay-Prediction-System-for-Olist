package com.olist.datasets.entity;

import com.olist.datasets.enums.RuleWorkbookStatus;
import java.time.Instant;
import java.util.UUID;

public class RuleWorkbook {

    private UUID id;
    private String ownerId;
    private String name;
    private String description;
    private UUID datasetVersionId;
    private RuleWorkbookStatus status;
    private Instant createdAt;
    private Instant updatedAt;

    public UUID getId() { return id; }
    public void setId(UUID id) { this.id = id; }
    public String getOwnerId() { return ownerId; }
    public void setOwnerId(String ownerId) { this.ownerId = ownerId; }
    public String getName() { return name; }
    public void setName(String name) { this.name = name; }
    public String getDescription() { return description; }
    public void setDescription(String description) { this.description = description; }
    public UUID getDatasetVersionId() { return datasetVersionId; }
    public void setDatasetVersionId(UUID datasetVersionId) { this.datasetVersionId = datasetVersionId; }
    public RuleWorkbookStatus getStatus() { return status; }
    public void setStatus(RuleWorkbookStatus status) { this.status = status; }
    public Instant getCreatedAt() { return createdAt; }
    public void setCreatedAt(Instant createdAt) { this.createdAt = createdAt; }
    public Instant getUpdatedAt() { return updatedAt; }
    public void setUpdatedAt(Instant updatedAt) { this.updatedAt = updatedAt; }
}